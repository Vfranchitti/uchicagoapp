"""Pre-modeling data-quality audit, organized by the total-error framework.

Foster et al., "Big Data and Social Science," ch. 10, split total error
into row error (coverage: omissions, duplicates, false inclusions), column
error (specification: does a variable measure what we assume?) and cell
error (measurement: is each value valid?). This audit runs the checks in
that order, preceded by a data-type inventory and a provenance review, and
followed by label completeness, coverage, and outside benchmarks.

Checks already defined in run_data_checks.py are reused, not rewritten.

Outputs
-------
outputs/tables/data_type_inventory.csv
outputs/tables/quality_audit.{csv,md}
"""
