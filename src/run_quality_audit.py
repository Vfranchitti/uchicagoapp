METADATA_TEXT_COLUMNS = ('clip_id', 'site_id', 'logger_model',
                         'pipe_material', 'recorded_at', 'labeled', 'label')


def _in_section(section, check_result):
    """Tag a check result with its audit section."""
    return {'section': section, **check_result}


# ---------------------------------------------------------------------------
# 1. Data types
# ---------------------------------------------------------------------------
def build_data_type_inventory(metadata, example_clip):
    """One row per variable: kind of data, origin, and observed values."""
    def describe_levels(column):
        return ', '.join(f'{level} ({count})' for level, count in
                         metadata[column].replace('', '(blank)')
                         .value_counts().items())

    by_night_order = metadata.sort_values('overnight_hour')['recorded_at']
    earliest, latest = by_night_order.iloc[0], by_night_order.iloc[-1]
    rows = [
        ('clip_id', 'Identifier (text)', 'Assigned by the pilot',
         f'{metadata["clip_id"].nunique()} unique, L01-L06 and U01-U40'),
        ('site_id', 'Identifier (text)', 'Hydrant asset ID, likely from '
         'city records', f'{metadata["site_id"].nunique()} unique'),
        ('logger_model', 'Categorical, 2 levels', 'Recorded by crew',
         describe_levels('logger_model')),
        ('pipe_material', 'Categorical, 2 levels', 'Likely from city asset '
         'records', describe_levels('pipe_material')),
        ('recorded_at', 'Clock time (HH:MM, text)', 'Logger clock or crew '
         'log', f'{earliest} to {latest} (overnight, spans midnight)'),
        ('labeled', 'Binary flag (yes/no)', 'Derived from dig records',
         describe_levels('labeled')),
        ('label', 'Binary outcome (leak/no_leak) with blanks',
         'Dig outcome recorded by crews', describe_levels('label')),
        ('time_s', 'Continuous (seconds)', 'Generated by logger sampling',
         f'{example_clip["time_s"].min():.4f}-'
         f'{example_clip["time_s"].max():.4f} s per clip'),
        ('amplitude', 'Continuous time series (float)', 'Sensor output, '
         'automated', f'{len(example_clip):,} values per clip, scaled to '
         f'[-{AMPLITUDE_LIMIT:.0f}, {AMPLITUDE_LIMIT:.0f}]'),
        ('.wav audio', 'Binary audio (16-bit integer PCM)', 'Sensor output, '
         'automated', 'Same signal as the CSV (checked below)'),
    ]
    return pd.DataFrame(rows, columns=['variable', 'data_type', 'origin',
                                       'observed_values'])


# ---------------------------------------------------------------------------
# 2. Provenance: signs of manual entry
# ---------------------------------------------------------------------------
def check_text_hygiene():
    """Stray spaces, odd capitalization, or duplicate spellings in metadata.

    Read without type conversion, so every cell is checked exactly as typed.
    """
    raw = pd.read_csv(METADATA_PATH, dtype=str, keep_default_na=False)
    problems = []
    for column in METADATA_TEXT_COLUMNS:
        values = raw[column]
        n_padded = int((values != values.str.strip()).sum())
        if n_padded:
            problems.append(f'{column}: {n_padded} cells with stray spaces')
        spellings = values.str.strip()
        n_case_variants = (spellings.nunique()
                           - spellings.str.lower().nunique())
        if n_case_variants:
            problems.append(f'{column}: {n_case_variants} capitalization '
                            'variants')
    return make_check_result(
        'Text hygiene (spaces, capitalization variants)',
        'Cell (measurement)', FLAG if problems else PASS,
        f'Problems: {problems or "none"}. Note that the two pipe codes use '
        'different styles ("cast_iron" vs. "PVC"); both match the '
        'documentation.')


def check_identifier_formats(metadata):
    """IDs and times follow one consistent, documented format."""
    patterns = {'site_id': SITE_ID_PATTERN, 'clip_id': CLIP_ID_PATTERN,
                'recorded_at': CLOCK_TIME_PATTERN}
    mismatches = {
        column: metadata.loc[~metadata[column].str.match(pattern),
                             column].tolist()
        for column, pattern in patterns.items()}
    mismatches = {k: v for k, v in mismatches.items() if v}
    bad_flags = metadata.loc[~metadata['labeled'].isin(VALID_LABELED_FLAGS),
                             'labeled'].tolist()
    is_ok = not mismatches and not bad_flags
    return make_check_result(
        'Identifier and time formats', 'Cell (measurement)',
        PASS if is_ok else FLAG,
        f'site_id matches HYD-####, clip_id matches L##/U##, recorded_at '
        f'matches HH:MM (00:00-23:59). Mismatches: {mismatches or "none"}; '
        f'invalid labeled flags: {bad_flags or "none"}.')


def check_time_heaping(metadata):
    """Do recording minutes pile up on round numbers (a typing signature)?"""
    minutes = metadata['recorded_at'].str[-2:].astype(int)
    n_round = int((minutes % ROUND_MINUTE_DIVISOR == 0).sum())
    test = stats.binomtest(n_round, len(minutes),
                           EXPECTED_ROUND_MINUTE_SHARE,
                           alternative='greater')
    is_heaped = test.pvalue < SIGNIFICANCE_LEVEL
    return make_check_result(
        'Round-minute heaping in recorded_at', 'Cell (measurement)',
        FLAG if is_heaped else PASS,
        f'{n_round} of {len(minutes)} times end in :x0 or :x5 '
        f'({n_round / len(minutes):.0%}; about '
        f'{EXPECTED_ROUND_MINUTE_SHARE:.0%} expected by chance, one-sided '
        f'binomial p = {test.pvalue:.2f}). No sign that times were rounded '
        f'by hand; they look like device clock stamps. The task says only '
        f'"local time, 24-hour clock," so each value is assumed to be the '
        f'start of the 5-second clip.')


def check_provenance_notes():
    """What the task document says about how each part was generated."""
    return make_check_result(
        'How the data were generated (from the task document)',
        'Column (specification)', INFO,
        'Audio is machine-generated: "cheap acoustic loggers were clipped '
        'to fire hydrants... and left overnight to record short clips," so '
        'amplitude values were not hand-entered. Metadata were assembled by '
        'people: crews chose which logger to use ("that\'s what we had in '
        'the shop," i.e., not random), pipe material most likely comes from '
        'asset records, and labels come from dig outcomes. Working '
        'assumptions (not stated in the task): each logger recorded one '
        '5-second clip per site, likely a cost or device limit, so there is '
        'no repeat measurement to average; clip timing was effectively '
        'random, so recording time should be unrelated to leak status; and '
        'loggers were split in proportion across pipe types and assigned '
        'randomly within each pipe type ("what we had in the shop"), so '
        'A/B differences reflect the device, not the site. Still unknown: '
        'how the 6 dug sites were chosen.')


# ---------------------------------------------------------------------------
# 3. Rows: false inclusions
# ---------------------------------------------------------------------------
def check_false_inclusions(metadata, amplitudes):
    """Rows that are present but may not be valid pipe recordings."""
    is_overnight = metadata['overnight_hour'].between(*OVERNIGHT_WINDOW_HOURS)
    outside_night = metadata.loc[~is_overnight, 'clip_id'].tolist()
    unusable = sorted(
        clip_id for clip_id, amplitude in amplitudes.items()
        if np.mean(np.abs(amplitude) >= CLIPPING_THRESHOLD)
        > MAX_CLIPPED_SHARE
        or find_longest_constant_run(amplitude)[1]
        > MAX_ALLOWED_FLATLINE_SAMPLES)
    return make_check_result(
        'False inclusions (rows that are not usable pipe recordings)',
        'Row (coverage)', FLAG if unusable or outside_night else PASS,
        f'Recordings outside the 8 pm-8 am overnight window: '
        f'{outside_night or "none"}. Recordings partly unusable because '
        f'the sensor overloaded or dropped out: {unusable or "none"}. Rows '
        f'kept, but these clips are flagged in the predictions.')


def check_logger_allocation(metadata):
    """Loggers spread in proportion across pipe types and through the night.

    Supports the working assumption that A/B differences reflect the
    device, not the kind of site or the time of recording.
    """
    by_pipe = pd.crosstab(metadata['logger_model'],
                          metadata['pipe_material'])
    pipe_test = stats.fisher_exact(by_pipe.to_numpy())
    pvc_shares = (by_pipe['PVC'] / by_pipe.sum(axis=1)).to_dict()
    hours = {logger: metadata.loc[metadata['logger_model'] == logger,
                                  'overnight_hour']
             for logger in LOGGER_MODELS}
    time_test = stats.mannwhitneyu(*hours.values())
    commute_shares = metadata.groupby('logger_model')[
        'is_commute_hours'].mean().to_dict()
    medians = {logger: _format_hour(values.median())
               for logger, values in hours.items()}
    is_balanced = min(pipe_test.pvalue,
                      time_test.pvalue) >= SIGNIFICANCE_LEVEL
    pvc_text = ', '.join(f'{k} {v:.0%}' for k, v in pvc_shares.items())
    commute_text = ', '.join(f'{k} {v:.0%}'
                             for k, v in commute_shares.items())
    return make_check_result(
        'Logger allocation by pipe type and recording time',
        'Column (specification)', PASS if is_balanced else FLAG,
        f'PVC share by logger: {pvc_text} (Fisher exact p = '
        f'{pipe_test.pvalue:.2f}). Median recording time: {medians} '
        f'(Mann-Whitney p = {time_test.pvalue:.2f}); share recorded at or '
        f'after 6 am: {commute_text}. A balanced result means there is no '
        f'sign that one logger was used on a different kind of site or at '
        f'a different time of night.')


def _format_hour(overnight_hour):
    """Overnight hour (evening negative) to 'H:MM am/pm'."""
    clock_minutes = round((overnight_hour % HOURS_PER_DAY)
                          * MINUTES_PER_HOUR)
    hour, minute = divmod(clock_minutes, MINUTES_PER_HOUR)
    suffix = 'am' if hour < HOURS_PER_DAY / 2 else 'pm'
    return f'{hour % 12 or 12}:{minute:02d} {suffix}'


# ---------------------------------------------------------------------------
# 4. Columns: does each variable measure what we assume?
# ---------------------------------------------------------------------------
def check_label_meaning():
    """What 'leak' and 'no_leak' actually record."""
    return make_check_result(
        'What the label measures', 'Column (specification)', INFO,
        'The label is the outcome of a dig, not of an independent '
        'inspection. "no_leak" means a crew dug and found nothing; a small '
        'or intermittent leak could be missed, so a few no_leak labels may '
        'be false negatives. All 6 labels were recorded after digging, so '
        'they cannot have influenced which site was dug.')


def check_pipe_material_meaning(metadata):
    """Pipe material is assumed accurate but cannot be verified here."""
    n_pvc = int((metadata['pipe_material'] == 'PVC').sum())
    return make_check_result(
        'What pipe_material measures', 'Column (specification)', INFO,
        f'Assumed to describe the main the hydrant sits on. It cannot be '
        f'checked against the audio, and no dug site is PVC, so the effect '
        f'of pipe material on what a leak sounds like is unknown for '
        f'{n_pvc} sites.')


# ---------------------------------------------------------------------------
# 5. Cells: values that are valid but unusual
# ---------------------------------------------------------------------------
def check_noise_floor_cluster(clip_features):
    """Very quiet, featureless clips: sensor self-noise, not errors."""
    is_quiet = clip_features['rms_loudness'] < NOISE_FLOOR_RMS
    quiet = clip_features[is_quiet]
    loggers = quiet['logger_model'].value_counts().to_dict()
    pipes = quiet['pipe_material'].value_counts().to_dict()
    return make_check_result(
        'Unusually quiet recordings (sensor noise floor)',
        'Cell (measurement)', INFO,
        f'{len(quiet)} of {len(clip_features)} clips have RMS below '
        f'{NOISE_FLOOR_RMS} (range {quiet["rms_loudness"].min():.4f}-'
        f'{quiet["rms_loudness"].max():.4f}) and near-zero spikiness '
        f'(median excess kurtosis {quiet["excess_kurtosis"].median():.2f}), '
        f'i.e., even, featureless noise. By logger: {loggers}; by pipe: '
        f'{pipes}. All undug: {not quiet["is_labeled"].any()}. Most likely '
        f'the logger\'s own electronic noise when the pipe is silent. These '
        f'are valid values, but "steady hiss" features will rate them as '
        f'steady, so steadiness must be combined with loudness or pitch.')


def check_documented_specifications(metadata, clip_tables):
    """Totals and formats against the task document (outside benchmark)."""
    n_labeled = int(metadata['is_labeled'].sum())
    durations = {clip_id: len(df) / SAMPLE_RATE_HZ
                 for clip_id, df in clip_tables.items()}
    is_ok = (len(metadata) == N_CLIPS_EXPECTED
             and n_labeled == N_LABELED_EXPECTED
             and len(metadata) - n_labeled == N_UNLABELED_EXPECTED
             and all(len(df) == SAMPLES_PER_CLIP
                     for df in clip_tables.values())
             and set(metadata['logger_model']) <= set(LOGGER_MODELS)
             and set(metadata['pipe_material']) <= set(PIPE_MATERIALS))
    return make_check_result(
        'Totals and formats vs. the task document', 'Row (coverage)',
        PASS if is_ok else FLAG,
        f'Document: 46 recordings (6 dug, 40 not), 5 s at 4,000 Hz = 20,000 '
        f'rows, amplitude in [-1, 1], loggers A/B, pipes cast_iron/PVC. '
        f'Data: {len(metadata)} recordings ({n_labeled} dug, '
        f'{len(metadata) - n_labeled} not); clip lengths range '
        f'{min(durations.values()):.2f}-{max(durations.values()):.2f} s '
        f'(documented {CLIP_DURATION_SECONDS} s). No external dataset '
        f'exists to check site-level values against.')


# ---------------------------------------------------------------------------
# 6. Labels
# ---------------------------------------------------------------------------
def check_missing_labels(metadata):
    """Every dug site has a label; no undug site has one."""
    labeled = metadata[metadata['is_labeled']]
    unlabeled = metadata[~metadata['is_labeled']]
    n_missing = int((~labeled['label'].isin(VALID_LABELS)).sum())
    n_spurious = int((unlabeled['label'] != '').sum())
    is_ok = n_missing == 0 and n_spurious == 0
    return make_check_result(
        'Missing or spurious labels', 'Cell (measurement)',
        PASS if is_ok else FLAG,
        f'Dug sites missing a label: {n_missing} of {len(labeled)}. Undug '
        f'sites carrying a label: {n_spurious} of {len(unlabeled)}. The 40 '
        f'blank labels are missing by design (not yet dug), not data loss.')


# ---------------------------------------------------------------------------
# 7-8. Benchmarks and base rates
# ---------------------------------------------------------------------------
def check_labeled_share_vs_base_rate(metadata):
    """Could the 6 dug sites be a random draw at the historical rate?"""
    labeled = metadata[metadata['is_labeled']]
    n_leaks = int((labeled['label'] == LEAK_LABEL).sum())
    test = stats.binomtest(n_leaks, len(labeled), HISTORICAL_LEAK_RATE,
                           alternative='greater')
    return make_check_result(
        'Dug-site leak share vs. the 1-in-8 benchmark', 'Row (coverage)',
        FLAG if test.pvalue < SIGNIFICANCE_LEVEL else PASS,
        f'{n_leaks} of {len(labeled)} dug sites leaked '
        f'({n_leaks / len(labeled):.0%}) vs. {HISTORICAL_LEAK_RATE:.1%} '
        f'historically. Chance of {n_leaks}+ leaks in {len(labeled)} '
        f'randomly chosen sites: {test.pvalue:.1%}. The dug sites were '
        f'almost certainly chosen because they seemed suspicious, so they '
        f'over-represent leaks; any probabilities learned from them must be '
        f're-anchored to 1 in 8.')


def run_quality_audit():
    """Run the full audit and save the inventory and results tables."""
    metadata = load_metadata()
    clip_tables = {
        clip_id: load_clip_csv(clip_id, is_labeled)
        for clip_id, is_labeled in zip(metadata['clip_id'],
                                       metadata['is_labeled'])}
    amplitudes = {clip_id: df['amplitude'].to_numpy()
                  for clip_id, df in clip_tables.items()}
    clip_features = build_clip_feature_table(metadata, amplitudes)
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    build_data_type_inventory(metadata, next(iter(clip_tables.values()))
                              ).to_csv(DATA_TYPE_INVENTORY_PATH, index=False)
    sections = [
        ('2 Provenance', [check_provenance_notes(), check_text_hygiene(),
                          check_identifier_formats(metadata),
                          check_time_heaping(metadata)]),
        ('3 Rows', [check_file_inventory(metadata),
                    check_unique_identifiers(metadata),
                    check_duplicate_recordings(amplitudes),
                    check_false_inclusions(metadata, amplitudes),
                    check_logger_allocation(metadata)]),
        ('4 Columns', [check_metadata_domains(metadata),
                       check_label_meaning(),
                       check_pipe_material_meaning(metadata),
                       check_logger_effect(clip_features),
                       check_clock_time_effect(clip_features),
                       check_label_confounding(metadata)]),
        ('5 Cells', [check_signal_shape(clip_tables),
                     check_time_grid(clip_tables),
                     check_amplitude_range(amplitudes),
                     check_csv_matches_wav(metadata, amplitudes),
                     check_clipping(amplitudes),
                     check_dropouts(amplitudes),
                     check_offset_and_silence(amplitudes, clip_features),
                     check_noise_floor_cluster(clip_features)]),
        ('6 Labels', [check_label_integrity(metadata),
                      check_missing_labels(metadata)]),
        ('7 Coverage', [check_coverage(metadata)]),
        ('8 Benchmarks', [check_documented_specifications(metadata,
                                                          clip_tables),
                          check_labeled_share_vs_base_rate(metadata)]),
    ]
    audit_rows = [_in_section(section, result)
                  for section, results in sections for result in results]
    return write_check_tables(audit_rows, QUALITY_AUDIT_CSV_PATH,
                              QUALITY_AUDIT_MARKDOWN_PATH)


if __name__ == '__main__':
    audit = run_quality_audit()
    with pd.option_context('display.max_colwidth', 140,
                           'display.width', 220):
        print(audit[['order', 'section', 'check', 'status']])
    print(f'Saved {QUALITY_AUDIT_MARKDOWN_PATH}')
